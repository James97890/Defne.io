const $ = s => document.querySelector(s);
let token = 0;

function type(el, text, done) {
  const my = ++token; el.textContent = '';
  let i = 0;
  (function tick() {
    if (my !== token) return;
    el.textContent = text.slice(0, ++i);
    if (i < text.length) setTimeout(tick, 28); else done && done();
  })();
}



function go(id) {
  document.querySelectorAll('.scene').forEach(s => s.classList.toggle('active', s.id === id));
  $('#' + id).scrollTop = 0;
  token++;

  const vid = $('#vid');
  if (vid && id !== 'song' && !vid.paused) {
    vid.pause();
    if (typeof bgm !== 'undefined' && bgm) {
      bgm.play().catch(() => {});
    }
  }

  if (id === 'memories') {
    const nxt = $('#memories .after'); nxt.classList.remove('show');
    type($('#mtext'), MEMORIES_TEXT, () => nxt.classList.add('show'));
  }
  if (id === 'flowers') type($('#ftext'), FLOWERS_TEXT);
  if (id === 'song' && vid) {
    if (!vid.src && typeof VIDEO_SRC !== 'undefined') vid.src = VIDEO_SRC;
    vid.play().catch(() => {});
  }
}

document.addEventListener('click', e => {
  const t = e.target.closest('[data-go]');
  if (t) go(t.dataset.go);
});

const bgm = document.getElementById('bgm');

function startBgm() {
  if (!bgm) return;
  bgm.volume = 0.5; // громкость от 0.0 до 1.0
  bgm.play().catch(() => {});
}

window.addEventListener('DOMContentLoaded', startBgm);
document.addEventListener('pointerdown', startBgm, { once: true });
